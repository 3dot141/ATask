package com.yes365.atask.ui.i18n

/**
 * The Chinese text for the English strings still written inline in the screens.
 *
 * The app has a typed [Strings] layer for the shell, but most screens and dialogs still carry
 * their text as English literals. Rewriting every screen to a typed field would be a large
 * refactor; this table is the smaller step that makes the whole app readable in Chinese: call
 * sites wrap the literal in [t] and the table supplies the translation.
 *
 * [setLanguage] is set once at the app root from the same locale that picks [Strings]. The app
 * has no in-app language switch, so a plain object is enough (iOS restarts the app when the
 * system language changes).
 */
